"""
Stroke - Core data structure for a single brush stroke.

A Stroke represents a single mark made by a brush, with mathematical
representation of its path, properties, and rendering parameters.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from enum import Enum
from typing import List, Tuple, Optional, Dict, Any, Iterator
import numpy as np
from numpy.typing import NDArray


class StrokeType(Enum):
    """Types of strokes based on their generation method."""
    PREDICTED = "predicted"      # Generated by neural network
    OPTIMIZED = "optimized"      # Refined via differentiable rendering
    INTERACTIVE = "interactive"  # User-defined or edited
    PROCEDURAL = "procedural"    # Generated by rule-based system


@dataclass
class Stroke:
    """
    Represents a single brush stroke with full mathematical representation.
    
    A stroke is defined by:
    - A Bezier path (control points)
    - Width profile along the path
    - Color/opacity
    - Brush type and physics parameters
    
    Attributes:
        id: Unique identifier for this stroke
        type: How this stroke was generated
        layer_id: Which layer this stroke belongs to
        brush_id: Reference to the brush used
        path: Control points as list of (x, y) tuples
        width: Base width of the stroke
        width_profile: Width multiplier at each point (for pressure/taper)
        color: RGB color as (r, g, b) in [0, 1]
        opacity: Opacity in [0, 1]
        angle: Rotation of the brush
        pressure_curve: Pressure modulation along the stroke
        render_order: Order in which this stroke should be rendered
        metadata: Additional data (source, confidence, etc.)
    """
    
    # Core identity
    id: str = field(default_factory=lambda: f"stroke_{uuid.uuid4().hex[:8]}")
    type: StrokeType = StrokeType.PREDICTED
    
    # Layer assignment
    layer_id: str = "default"
    
    # Brush reference
    brush_id: str = "default_brush"
    
    # Path representation
    path: List[Tuple[float, float]] = field(default_factory=list)
    num_points: int = 0  # Number of sampled points along the stroke
    
    # Width properties
    width: float = 10.0  # Base width in pixels
    width_profile: Optional[NDArray[np.float32]] = None  # Width variation
    
    # Color properties
    color: Tuple[float, float, float] = (0.0, 0.0, 0.0)  # RGB [0, 1]
    opacity: float = 1.0
    
    # Brush properties
    angle: float = 0.0  # Brush rotation in radians
    pressure: float = 1.0  # Base pressure
    pressure_curve: Optional[NDArray[np.float32]] = None  # Pressure modulation
    
    # Rendering
    render_order: int = 0
    
    # Metadata
    metadata: Dict[str, Any] = field(default_factory=dict)
    
    def __post_init__(self):
        """Validate and initialize derived properties."""
        if self.path:
            self.num_points = len(self.path)
            
        # Initialize default profiles if not provided
        if self.width_profile is None and self.num_points > 0:
            self.width_profile = np.ones(self.num_points, dtype=np.float32)
            
        if self.pressure_curve is None and self.num_points > 0:
            self.pressure_curve = np.ones(self.num_points, dtype=np.float32)
    
    def add_point(self, x: float, y: float) -> None:
        """Add a point to the stroke path."""
        self.path.append((x, y))
        self.num_points = len(self.path)
        
        # Extend profiles
        if self.width_profile is not None:
            self.width_profile = np.append(
                self.width_profile, self.width_profile[-1] if len(self.width_profile) > 0 else 1.0
            )
        if self.pressure_curve is not None:
            self.pressure_curve = np.append(
                self.pressure_curve, self.pressure_curve[-1] if len(self.pressure_curve) > 0 else 1.0
            )
    
    def get_effective_widths(self) -> NDArray[np.float32]:
        """Calculate effective width at each point considering profile and pressure."""
        if self.width_profile is None:
            profile = np.ones(self.num_points, dtype=np.float32)
        else:
            profile = self.width_profile
            
        if self.pressure_curve is None:
            pressure = np.ones(self.num_points, dtype=np.float32)
        else:
            pressure = self.pressure_curve
            
        return self.width * profile * pressure * self.pressure
    
    def get_bounding_box(self) -> Tuple[float, float, float, float]:
        """Return (min_x, min_y, max_x, max_y) bounding box."""
        if not self.path:
            return (0, 0, 0, 0)
        xs = [p[0] for p in self.path]
        ys = [p[1] for p in self.path]
        return (min(xs), min(ys), max(xs), max(ys))
    
    def get_length(self) -> float:
        """Calculate total path length."""
        if len(self.path) < 2:
            return 0.0
        total = 0.0
        for i in range(1, len(self.path)):
            dx = self.path[i][0] - self.path[i-1][0]
            dy = self.path[i][1] - self.path[i-1][1]
            total += np.sqrt(dx*dx + dy*dy)
        return total
    
    def sample_points(self, num_samples: int) -> List[Tuple[float, float, float]]:
        """
        Sample the stroke at regular intervals.
        
        Returns:
            List of (x, y, t) where t is the normalized position [0, 1]
        """
        if len(self.path) < 2:
            return [(self.path[0][0], self.path[0][1], 0.0)] if self.path else []
        
        # Calculate cumulative distances
        distances = [0.0]
        for i in range(1, len(self.path)):
            dx = self.path[i][0] - self.path[i-1][0]
            dy = self.path[i][1] - self.path[i-1][1]
            distances.append(distances[-1] + np.sqrt(dx*dx + dy*dy))
        
        total_length = distances[-1]
        if total_length == 0:
            return [(self.path[0][0], self.path[0][1], 0.0)]
        
        # Sample at regular intervals
        samples = []
        for i in range(num_samples):
            t = i / (num_samples - 1) if num_samples > 1 else 0
            target_dist = t * total_length
            
            # Find the segment
            for j in range(1, len(distances)):
                if distances[j] >= target_dist:
                    segment_t = (target_dist - distances[j-1]) / (distances[j] - distances[j-1])
                    x = self.path[j-1][0] + segment_t * (self.path[j][0] - self.path[j-1][0])
                    y = self.path[j-1][1] + segment_t * (self.path[j][1] - self.path[j-1][1])
                    samples.append((x, y, t))
                    break
                    
        return samples
    
    def to_dict(self) -> Dict[str, Any]:
        """Serialize to dictionary for .stroke format."""
        return {
            "id": self.id,
            "type": self.type.value,
            "layer_id": self.layer_id,
            "brush_id": self.brush_id,
            "path": [[float(x), float(y)] for x, y in self.path],
            "num_points": self.num_points,
            "width": float(self.width),
            "width_profile": self.width_profile.tolist() if self.width_profile is not None else None,
            "color": list(self.color),
            "opacity": float(self.opacity),
            "angle": float(self.angle),
            "pressure": float(self.pressure),
            "pressure_curve": self.pressure_curve.tolist() if self.pressure_curve is not None else None,
            "render_order": self.render_order,
            "metadata": self.metadata,
        }
    
    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> Stroke:
        """Deserialize from dictionary."""
        stroke = cls(
            id=data.get("id", f"stroke_{uuid.uuid4().hex[:8]}"),
            type=StrokeType(data.get("type", "predicted")),
            layer_id=data.get("layer_id", "default"),
            brush_id=data.get("brush_id", "default_brush"),
            path=[(float(x), float(y)) for x, y in data.get("path", [])],
            num_points=data.get("num_points", 0),
            width=float(data.get("width", 10.0)),
            color=tuple(data.get("color", [0, 0, 0])),
            opacity=float(data.get("opacity", 1.0)),
            angle=float(data.get("angle", 0.0)),
            pressure=float(data.get("pressure", 1.0)),
            render_order=data.get("render_order", 0),
            metadata=data.get("metadata", {}),
        )
        
        if data.get("width_profile") is not None:
            stroke.width_profile = np.array(data["width_profile"], dtype=np.float32)
        if data.get("pressure_curve") is not None:
            stroke.pressure_curve = np.array(data["pressure_curve"], dtype=np.float32)
            
        return stroke
    
    def clone(self) -> Stroke:
        """Create a deep copy of this stroke."""
        return Stroke.from_dict(self.to_dict())
